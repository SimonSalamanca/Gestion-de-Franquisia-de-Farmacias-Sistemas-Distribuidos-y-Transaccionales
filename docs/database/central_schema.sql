       AND NOT EXISTS (SELECT 1 FROM empleado WHERE id_empleado = NEW.id_empleado) THEN
        RAISE EXCEPTION 'El empleado % no existe (auditoría del central)', NEW.id_empleado USING ERRCODE = '23503';
    END IF;
    RETURN NEW;
