-- HU-04: alertas de stock bajo y de caducidad, y bloqueo automático de lotes vencidos. Idempotente.
-- Todo es local: funciona sin conexión con el central (RNF-04). Los umbrales llegan por réplica (umbral_stock_ref).

-- El bloqueo automático lo hace el sistema, no una persona: la auditoría admite un actor nulo (el central ya lo admite).
ALTER TABLE registro_actividad
    ALTER COLUMN id_empleado DROP NOT NULL;

-- Una fila por alerta. Una alerta activa por (tipo, medicamento, lote): si la condición sigue, se actualiza; si deja de
-- cumplirse (se repone el stock, el lote se agota o se da de baja), se resuelve sola y queda el historial.
CREATE TABLE IF NOT EXISTS alerta (
    id_alerta bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo character varying(30) NOT NULL,
    id_medicamento integer NOT NULL REFERENCES medicamento_ref (id_medicamento),
    -- Sin clave foránea a lote: la FK toma un bloqueo de la fila del lote que choca con el FOR UPDATE de una venta, y
    -- la evaluación esperaría a las ventas (y podría interbloquearse con ellas). La alerta solo guarda el número.
    id_lote integer,
    nivel character varying(10) NOT NULL,
    prioridad numeric NOT NULL DEFAULT 0,
    detalle jsonb NOT NULL DEFAULT '{}'::jsonb,
    estado character varying(10) NOT NULL DEFAULT 'ACTIVA',
    creada_en timestamp without time zone NOT NULL DEFAULT now(),
    actualizada_en timestamp without time zone NOT NULL DEFAULT now(),
    resuelta_en timestamp without time zone,
    id_empleado_vista integer REFERENCES empleado_ref (id_empleado),
    vista_en timestamp without time zone,
    CONSTRAINT alerta_tipo_check CHECK (tipo IN ('LOTE_VENCIDO', 'STOCK_AGOTADO', 'STOCK_BAJO', 'CADUCIDAD_PROXIMA', 'SIN_UMBRAL')),
    CONSTRAINT alerta_nivel_check CHECK (nivel IN ('CRITICA', 'ALTA', 'MEDIA')),
    CONSTRAINT alerta_estado_check CHECK (estado IN ('ACTIVA', 'RESUELTA'))
);

ALTER TABLE alerta
    DROP CONSTRAINT IF EXISTS alerta_id_lote_fkey;

CREATE UNIQUE INDEX IF NOT EXISTS uq_alerta_activa ON alerta (tipo, id_medicamento, (coalesce(id_lote, 0))) WHERE estado = 'ACTIVA';
CREATE INDEX IF NOT EXISTS idx_alerta_estado ON alerta (estado, nivel);

-- Qué debe estar alertado AHORA, según los datos. Es la única definición de las reglas.
--   LOTE_VENCIDO      CRITICA  fecha de caducidad ya cumplida (< hoy) y aún con unidades; el lote queda bloqueado
--   STOCK_AGOTADO     CRITICA  sin unidades vendibles, con umbral configurado
--   CADUCIDAD_PROXIMA ALTA     faltan 7 días o menos; MEDIA dentro del periodo de aviso del umbral (30 días sin umbral)
--   STOCK_BAJO        ALTA     stock vendible hasta la mitad del mínimo; MEDIA entre la mitad y el mínimo (igual o menor)
--   SIN_UMBRAL        ALTA     medicamento activo sin umbral en esta tienda: nada lo vigila bien (no debería ocurrir)
-- Stock vendible = lotes DISPONIBLE y no vencidos (la misma regla de HU-01 y de la venta). prioridad ordena dentro de un
-- nivel: lo más vencido, lo más cercano a caducar o lo más escaso primero.
CREATE OR REPLACE VIEW alertas_calculadas AS
WITH stock AS (
    SELECT m.id_medicamento,
           coalesce(sum(l.cantidad_disponible) FILTER (WHERE l.estado = 'DISPONIBLE' AND l.fecha_caducidad >= current_date), 0)::int AS vendible
    FROM medicamento_ref m
    LEFT JOIN lote l ON l.id_medicamento = m.id_medicamento
    WHERE m.activo
    GROUP BY m.id_medicamento
)
SELECT 'LOTE_VENCIDO'::text AS tipo, l.id_medicamento, l.id_lote, 'CRITICA'::text AS nivel,
       (l.fecha_caducidad - current_date)::numeric AS prioridad,
       jsonb_build_object('numero_lote', l.numero_lote, 'cantidad', l.cantidad_disponible,
                          'fecha_caducidad', l.fecha_caducidad::text, 'dias_vencido', current_date - l.fecha_caducidad) AS detalle
FROM lote l
JOIN medicamento_ref m ON m.id_medicamento = l.id_medicamento AND m.activo
WHERE l.fecha_caducidad < current_date AND l.cantidad_disponible > 0
UNION ALL
SELECT 'CADUCIDAD_PROXIMA', l.id_medicamento, l.id_lote,
       CASE WHEN l.fecha_caducidad - current_date <= 7 THEN 'ALTA' ELSE 'MEDIA' END,
       (l.fecha_caducidad - current_date)::numeric,
       jsonb_build_object('numero_lote', l.numero_lote, 'cantidad', l.cantidad_disponible, 'fecha_caducidad', l.fecha_caducidad::text,
                          'dias_restantes', l.fecha_caducidad - current_date, 'dias_aviso', coalesce(u.dias_alerta_caducidad, 30))
FROM lote l
JOIN medicamento_ref m ON m.id_medicamento = l.id_medicamento AND m.activo
LEFT JOIN umbral_stock_ref u ON u.id_medicamento = l.id_medicamento
WHERE l.estado = 'DISPONIBLE' AND l.cantidad_disponible > 0 AND l.fecha_caducidad >= current_date
  AND l.fecha_caducidad - current_date <= coalesce(u.dias_alerta_caducidad, 30)
UNION ALL
SELECT CASE WHEN s.vendible = 0 THEN 'STOCK_AGOTADO' ELSE 'STOCK_BAJO' END, m.id_medicamento, NULL::integer,
       CASE WHEN s.vendible = 0 THEN 'CRITICA' WHEN s.vendible * 2 <= u.stock_minimo THEN 'ALTA' ELSE 'MEDIA' END,
       CASE WHEN u.stock_minimo > 0 THEN (s.vendible::numeric / u.stock_minimo) * 100 ELSE 0 END,
       jsonb_build_object('stock', s.vendible, 'stock_minimo', u.stock_minimo)
FROM medicamento_ref m
JOIN stock s ON s.id_medicamento = m.id_medicamento
JOIN umbral_stock_ref u ON u.id_medicamento = m.id_medicamento
WHERE m.activo AND (s.vendible = 0 OR (u.stock_minimo > 0 AND s.vendible <= u.stock_minimo))
UNION ALL
SELECT 'SIN_UMBRAL', m.id_medicamento, NULL::integer, 'ALTA', 0::numeric, '{}'::jsonb
FROM medicamento_ref m
WHERE m.activo AND NOT EXISTS (SELECT 1 FROM umbral_stock_ref u WHERE u.id_medicamento = m.id_medicamento);

-- Una pasada de evaluación, en una sola llamada (con la base remota cada ida y vuelta cuesta ~130 ms):
--   1. bloquea los lotes cuya caducidad ya se cumplió (criterio 3) y lo audita con el sistema como actor;
--   2. crea las alertas nuevas y actualiza las que siguen (criterios 1 y 2);
--   3. resuelve las que ya no aplican.
-- Es idempotente. Si otra evaluación está en curso devuelve { omitido: true } (el índice único evita duplicados de todas
-- formas). Los lotes que una venta tiene bloqueados en este instante se saltan (SKIP LOCKED) y se bloquean en la
-- siguiente pasada: el bloqueo nunca espera ni se interbloquea con una venta.
-- Devuelve los medicamentos cuyo stock vendible cambió al bloquear, para publicar el nuevo stock al central.
CREATE OR REPLACE FUNCTION evaluar_alertas() RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_medicamentos integer[];
    v_bloqueados integer;
    v_nuevas integer;
    v_resueltas integer;
BEGIN
    IF NOT pg_try_advisory_xact_lock(hashtext('hu04_evaluar_alertas')) THEN
        RETURN jsonb_build_object('omitido', true);
    END IF;

    WITH candidatos AS (
        SELECT id_lote FROM lote
         WHERE fecha_caducidad < current_date AND estado = 'DISPONIBLE'
         ORDER BY id_lote
         FOR UPDATE SKIP LOCKED
    ), bloqueados AS (
        UPDATE lote l SET estado = 'BLOQUEADO'
          FROM candidatos c
         WHERE l.id_lote = c.id_lote
        RETURNING l.id_lote, l.id_medicamento, l.numero_lote, l.cantidad_disponible
    ), auditoria AS (
        INSERT INTO registro_actividad (id_empleado, accion, entidad_afectada, id_entidad_afectada, detalle)
        SELECT NULL, 'LOTE_BLOQUEO_AUTOMATICO', 'lote', b.id_lote,
               left('Lote ' || b.numero_lote || ' vencido; ' || b.cantidad_disponible || ' unidad(es) bloqueadas para la venta', 400)
          FROM bloqueados b
        RETURNING 1
    )
    SELECT coalesce(array_agg(DISTINCT id_medicamento), '{}'::integer[]), count(*)
      INTO v_medicamentos, v_bloqueados
      FROM bloqueados;

    WITH aplicadas AS (
        INSERT INTO alerta (tipo, id_medicamento, id_lote, nivel, prioridad, detalle)
        SELECT tipo, id_medicamento, id_lote, nivel, prioridad, detalle FROM alertas_calculadas
        ON CONFLICT (tipo, id_medicamento, (coalesce(id_lote, 0))) WHERE estado = 'ACTIVA'
        DO UPDATE SET nivel = EXCLUDED.nivel, prioridad = EXCLUDED.prioridad, detalle = EXCLUDED.detalle, actualizada_en = now()
         WHERE alerta.nivel IS DISTINCT FROM EXCLUDED.nivel
            OR alerta.prioridad IS DISTINCT FROM EXCLUDED.prioridad
            OR alerta.detalle IS DISTINCT FROM EXCLUDED.detalle
        RETURNING (xmax = 0) AS nueva
    )
    SELECT count(*) FILTER (WHERE nueva) INTO v_nuevas FROM aplicadas;

    UPDATE alerta a
       SET estado = 'RESUELTA', resuelta_en = now(), actualizada_en = now()
     WHERE a.estado = 'ACTIVA'
       AND NOT EXISTS (
           SELECT 1 FROM alertas_calculadas c
            WHERE c.tipo = a.tipo AND c.id_medicamento = a.id_medicamento AND coalesce(c.id_lote, 0) = coalesce(a.id_lote, 0)
       );
    GET DIAGNOSTICS v_resueltas = ROW_COUNT;

    RETURN jsonb_build_object('bloqueados', v_bloqueados, 'medicamentos', to_jsonb(v_medicamentos), 'nuevas', v_nuevas, 'resueltas', v_resueltas);
END;
$$;
