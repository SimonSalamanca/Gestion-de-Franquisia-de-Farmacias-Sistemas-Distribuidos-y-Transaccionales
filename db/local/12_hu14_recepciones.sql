-- HU-14: recepción de mercancía vinculada a la solicitud, con constancia de las diferencias. Idempotente.
-- Todo es local: la tienda recibe y deja constancia aunque no alcance al central (RNF-04). Una recepción es un documento
-- propio (recepcion + detalle_recepcion) ligado al pedido original; las unidades siguen entrando por el servicio de
-- movimientos de HU-02 (lote, proveedor, movimiento ENTRADA con referencia PEDIDO-<id>).

CREATE TABLE IF NOT EXISTS recepcion (
    id_recepcion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido integer NOT NULL REFERENCES pedido (id_pedido),
    id_empleado integer NOT NULL REFERENCES empleado_ref (id_empleado),
    fecha_hora timestamp without time zone NOT NULL DEFAULT now(),
    documento_proveedor varchar(60),
    observaciones varchar(300)
);

-- Qué lote recibió cada línea: del lote se llega al proveedor, a la caducidad y a los movimientos.
CREATE TABLE IF NOT EXISTS detalle_recepcion (
    id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recepcion integer NOT NULL REFERENCES recepcion (id_recepcion),
    id_medicamento integer NOT NULL REFERENCES medicamento_ref (id_medicamento),
    id_lote integer NOT NULL REFERENCES lote (id_lote),
    id_proveedor integer NOT NULL REFERENCES proveedor_ref (id_proveedor),
    cantidad integer NOT NULL CHECK (cantidad > 0)
);

-- Constancia de que lo recibido no coincide con lo solicitado. diferencia < 0 es faltante (se cerró el pedido sin recibir
-- todo) y > 0 sobrante (llegó más de lo pedido). Guarda lo solicitado y lo recibido acumulado en ese instante, el motivo,
-- quién y cuándo; no se edita ni se borra. id_recepcion es nulo cuando el faltante se declara al cerrar el pedido sin
-- recibir nada nuevo.
CREATE TABLE IF NOT EXISTS diferencia_recepcion (
    id_diferencia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido integer NOT NULL REFERENCES pedido (id_pedido),
    id_recepcion integer REFERENCES recepcion (id_recepcion),
    id_medicamento integer NOT NULL REFERENCES medicamento_ref (id_medicamento),
    tipo varchar(10) NOT NULL,
    cantidad_solicitada integer NOT NULL,
    cantidad_recibida integer NOT NULL,
    diferencia integer NOT NULL,
    motivo varchar(300) NOT NULL,
    id_empleado integer NOT NULL REFERENCES empleado_ref (id_empleado),
    fecha_hora timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT diferencia_recepcion_tipo_check CHECK (
        (tipo = 'FALTANTE' AND diferencia < 0) OR (tipo = 'SOBRANTE' AND diferencia > 0)
    ),
    CONSTRAINT diferencia_recepcion_cuadra_check CHECK (diferencia = cantidad_recibida - cantidad_solicitada),
    CONSTRAINT diferencia_recepcion_motivo_check CHECK (char_length(btrim(motivo)) >= 5)
);

CREATE INDEX IF NOT EXISTS idx_recepcion_pedido ON recepcion (id_pedido, fecha_hora);
CREATE INDEX IF NOT EXISTS idx_detalle_recepcion_recepcion ON detalle_recepcion (id_recepcion);
CREATE INDEX IF NOT EXISTS idx_diferencia_recepcion_pedido ON diferencia_recepcion (id_pedido);

-- El pedido recuerda que tuvo diferencias (consulta rápida en la lista de solicitudes).
ALTER TABLE pedido ADD COLUMN IF NOT EXISTS con_diferencia boolean NOT NULL DEFAULT false;

-- Constancias inmutables, igual que la auditoría y las facturas: ni un UPDATE ni un DELETE las altera.
CREATE OR REPLACE FUNCTION recepcion_inmutable() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Una recepción registrada no se puede modificar ni borrar (% en %)', TG_OP, TG_TABLE_NAME
        USING ERRCODE = '42501';
END;
$$;

CREATE OR REPLACE TRIGGER recepcion_inmutable_trg
    BEFORE UPDATE OR DELETE ON recepcion
    FOR EACH ROW EXECUTE FUNCTION recepcion_inmutable();
CREATE OR REPLACE TRIGGER detalle_recepcion_inmutable_trg
    BEFORE UPDATE OR DELETE ON detalle_recepcion
    FOR EACH ROW EXECUTE FUNCTION recepcion_inmutable();
CREATE OR REPLACE TRIGGER diferencia_recepcion_inmutable_trg
    BEFORE UPDATE OR DELETE ON diferencia_recepcion
    FOR EACH ROW EXECUTE FUNCTION recepcion_inmutable();
