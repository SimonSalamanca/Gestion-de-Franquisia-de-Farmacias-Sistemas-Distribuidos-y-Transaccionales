CREATE TABLE IF NOT EXISTS empleado_ref_cuarentena (
    id_cuarentena bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado integer,
    id_rol integer,
    id_tienda integer,
    nombre_completo character varying(150),
    usuario character varying(60),
    activo boolean,
    contrasena_hash character varying(255),
    version_credencial bigint,
    motivo character varying(200) NOT NULL,
    movido_en timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sync_conflicto (
    id_conflicto bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado integer,
    tipo character varying(40) NOT NULL,
    detalle character varying(400) NOT NULL,
    creado_en timestamp with time zone NOT NULL DEFAULT now(),
    resuelto boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS permiso_ref (
    id_permiso integer PRIMARY KEY,
    codigo character varying(60) NOT NULL UNIQUE,
    descripcion character varying(200)
);

CREATE TABLE IF NOT EXISTS rol_permiso_ref (
    id_rol integer NOT NULL REFERENCES rol_ref (id_rol),
    id_permiso integer NOT NULL REFERENCES permiso_ref (id_permiso),
    PRIMARY KEY (id_rol, id_permiso)
);

CREATE TABLE IF NOT EXISTS control_acceso (
    id_empleado integer PRIMARY KEY REFERENCES empleado_ref (id_empleado),
    epoch bigint NOT NULL DEFAULT 1,
    intentos_en_epoch integer NOT NULL DEFAULT 0,
    estado character varying(20) NOT NULL DEFAULT 'ACTIVO',
    bloqueado_hasta timestamp with time zone,
    provisional boolean NOT NULL DEFAULT false,
    provisional_hasta timestamp with time zone,
    id_snapshot bigint NOT NULL DEFAULT 0,
    CONSTRAINT control_acceso_estado_check CHECK (estado IN ('ACTIVO', 'BLOQUEADO'))
);

CREATE TABLE IF NOT EXISTS intento_acceso (
    id_intento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key uuid NOT NULL UNIQUE,
    usuario_intentado character varying(60) NOT NULL,
    id_empleado integer,
    resultado character varying(40) NOT NULL,
    fecha_hora timestamp with time zone NOT NULL DEFAULT now(),
    detalle character varying(400)
);

CREATE TABLE IF NOT EXISTS auth_operacion (
    idempotency_key uuid PRIMARY KEY,
    payload_hmac character(64) NOT NULL,
    resultado_http integer NOT NULL,
    cuerpo_json jsonb NOT NULL,
    token_entrega text,
    creado_en timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sesion_activa (
    id_sesion uuid PRIMARY KEY,
    token_hash character(64) NOT NULL UNIQUE,
    id_empleado integer NOT NULL REFERENCES empleado_ref (id_empleado),
    id_tienda integer NOT NULL,
    nodo_emisor character varying(10) NOT NULL,
    expira_en timestamp with time zone NOT NULL,
    revocada boolean NOT NULL DEFAULT false,
    creado_en timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS outbox_sync (
    id_outbox bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado integer,
    idempotency_key uuid NOT NULL UNIQUE,
    tipo_evento character varying(40) NOT NULL,
    payload jsonb NOT NULL,
    estado character varying(20) NOT NULL DEFAULT 'PENDIENTE',
    intentos integer NOT NULL DEFAULT 0,
    proximo_intento timestamp with time zone NOT NULL DEFAULT now(),
    creado_en timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT outbox_sync_estado_check CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'ERROR'))
);

