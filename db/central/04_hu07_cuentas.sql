-- HU-07: cuentas de empleados, restablecimiento de contraseña y auditoría. Idempotente.

-- Control optimista de edición de la cuenta (dos administradores sobre el mismo empleado).
-- Distinta de version_credencial (HU-06), que solo cambia con la contraseña.
ALTER TABLE empleado
    ADD COLUMN IF NOT EXISTS version_cuenta bigint NOT NULL DEFAULT 1;

-- Códigos de un solo uso para restablecer la contraseña. Solo se guarda el HMAC del código.
CREATE TABLE IF NOT EXISTS codigo_restablecimiento (
    id_codigo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado integer NOT NULL REFERENCES empleado (id_empleado),
    codigo_hmac character(64) NOT NULL,
    estado character varying(12) NOT NULL DEFAULT 'VIGENTE',
    intentos integer NOT NULL DEFAULT 0,
    expira_en timestamp with time zone NOT NULL,
    generado_por integer NOT NULL REFERENCES empleado (id_empleado),
    creado_en timestamp with time zone NOT NULL DEFAULT now(),
    usado_en timestamp with time zone,
    CONSTRAINT codigo_restablecimiento_estado_check CHECK (estado IN ('VIGENTE', 'USADO', 'ANULADO', 'BLOQUEADO'))
);

CREATE INDEX IF NOT EXISTS idx_codigo_restablecimiento_vigente
    ON codigo_restablecimiento (id_empleado) WHERE estado = 'VIGENTE';

-- Auditoría que suben las tiendas. Clave (tienda, id local): un reenvío no duplica.
-- Sin FK a empleado ni tienda: es historia, debe sobrevivir a cambios del catálogo.
CREATE TABLE IF NOT EXISTS auditoria_tienda (
    id_tienda integer NOT NULL,
    id_registro integer NOT NULL,
    id_empleado integer,
    accion character varying(80) NOT NULL,
    entidad_afectada character varying(60) NOT NULL,
    id_entidad_afectada integer,
    fecha_hora timestamp without time zone NOT NULL,
    detalle character varying(400),
    recibido_en timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (id_tienda, id_registro)
);

CREATE INDEX IF NOT EXISTS idx_auditoria_tienda_fecha ON auditoria_tienda (fecha_hora);
CREATE INDEX IF NOT EXISTS idx_registro_actividad_central_fecha ON registro_actividad_central (fecha_hora);

-- Bitácora no editable (RNF-10): nada se actualiza; solo se borra lo que ya cumplió 2 años de retención.
-- fecha_hora es timestamp sin zona en UTC (Neon corre en GMT), igual que now()::timestamp.
CREATE OR REPLACE FUNCTION auditoria_inmutable() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' AND OLD.fecha_hora < now()::timestamp - interval '2 years' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'La auditoría no se puede modificar ni borrar (% en %)', TG_OP, TG_TABLE_NAME
        USING ERRCODE = '42501';
END;
$$;

CREATE OR REPLACE TRIGGER registro_actividad_central_inmutable
    BEFORE UPDATE OR DELETE ON registro_actividad_central
    FOR EACH ROW EXECUTE FUNCTION auditoria_inmutable();
CREATE OR REPLACE TRIGGER registro_actividad_central_sin_truncate
    BEFORE TRUNCATE ON registro_actividad_central
    FOR EACH STATEMENT EXECUTE FUNCTION auditoria_inmutable();
CREATE OR REPLACE TRIGGER auditoria_tienda_inmutable
    BEFORE UPDATE OR DELETE ON auditoria_tienda
    FOR EACH ROW EXECUTE FUNCTION auditoria_inmutable();
CREATE OR REPLACE TRIGGER auditoria_tienda_sin_truncate
    BEFORE TRUNCATE ON auditoria_tienda
    FOR EACH STATEMENT EXECUTE FUNCTION auditoria_inmutable();

-- Permiso para consultar la auditoría (RNF-11: es un dato). Mismo patrón que 02_hu02_permisos.sql.
DO $$
DECLARE
    v_cambio boolean := false;
    v_filas integer;
    v_permiso permiso%ROWTYPE;
    r record;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM permiso WHERE codigo = 'AUDITORIA_CONSULTAR') THEN
        PERFORM setval('permiso_id_permiso_seq', (SELECT COALESCE(MAX(id_permiso), 1) FROM permiso));
        INSERT INTO permiso (codigo, descripcion)
        VALUES ('AUDITORIA_CONSULTAR', 'Consultar el registro de auditoría');
        v_cambio := true;
    END IF;

    INSERT INTO rol_permiso (id_rol, id_permiso)
    SELECT r2.id_rol, p.id_permiso
    FROM rol r2
    JOIN permiso p ON p.codigo = 'AUDITORIA_CONSULTAR'
    WHERE r2.nombre IN ('administrador_tienda', 'administrador_general')
    ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS v_filas = ROW_COUNT;
    IF v_filas > 0 THEN
        v_cambio := true;
    END IF;

    IF v_cambio AND EXISTS (SELECT 1 FROM replica_evento) THEN
        SELECT * INTO v_permiso FROM permiso WHERE codigo = 'AUDITORIA_CONSULTAR';
        PERFORM append_replica_evento(
            NULL, 'PERMISO_UPSERT', 1,
            jsonb_build_object('id_permiso', v_permiso.id_permiso, 'codigo', v_permiso.codigo, 'descripcion', v_permiso.descripcion)
        );
        FOR r IN SELECT id_rol FROM rol WHERE nombre IN ('administrador_tienda', 'administrador_general') ORDER BY id_rol LOOP
            PERFORM append_replica_evento(
                NULL, 'ROL_PERMISO_SET', 1,
                jsonb_build_object(
                    'id_rol', r.id_rol,
                    'permisos', (
                        SELECT COALESCE(jsonb_agg(jsonb_build_object('id_permiso', p.id_permiso, 'codigo', p.codigo) ORDER BY p.codigo), '[]'::jsonb)
                        FROM rol_permiso rp
                        JOIN permiso p ON p.id_permiso = rp.id_permiso
                        WHERE rp.id_rol = r.id_rol
                    )
                )
            );
        END LOOP;
    END IF;
END $$;
