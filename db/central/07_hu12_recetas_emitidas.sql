-- HU-12 (validación contra el sistema de salud, simulada): el central hace de EPS. Guarda las recetas emitidas con su
-- código, confirma que son auténticas y vigentes, las reserva para una sola tienda y las da de baja al dispensarse,
-- de modo que no puedan usarse otra vez en otra sucursal. Idempotente.

-- Reserva y vigencia como datos, no código: se ajustan con un UPDATE.
CREATE TABLE IF NOT EXISTS politica_receta (
    id integer PRIMARY KEY,
    dias_vigencia integer NOT NULL,
    minutos_reserva integer NOT NULL,
    CONSTRAINT politica_receta_id_check CHECK (id = 1),
    CONSTRAINT politica_receta_dias_check CHECK (dias_vigencia > 0),
    CONSTRAINT politica_receta_reserva_check CHECK (minutos_reserva > 0)
);

INSERT INTO politica_receta (id, dias_vigencia, minutos_reserva)
VALUES (1, 30, 15)
ON CONFLICT (id) DO NOTHING;

CREATE OR REPLACE FUNCTION receta_vigente(p_fecha_emision date)
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
    SELECT p_fecha_emision <= current_date
       AND current_date - p_fecha_emision <= (SELECT dias_vigencia FROM politica_receta WHERE id = 1);
$$;

-- Receta emitida por el médico/EPS. Estados: EMITIDA (libre), RESERVADA (una tienda la tiene en caja, con plazo),
-- RECLAMADA (dada de baja: ya no sirve en ninguna tienda) y ANULADA.
CREATE TABLE IF NOT EXISTS receta_emitida (
    id_receta_emitida integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo character varying(40) NOT NULL UNIQUE,
    paciente_nombre character varying(150) NOT NULL,
    paciente_documento character varying(40) NOT NULL,
    medico_prescriptor character varying(150) NOT NULL,
    fecha_emision date NOT NULL,
    estado character varying(20) NOT NULL DEFAULT 'EMITIDA',
    id_tienda_reserva integer REFERENCES tienda (id_tienda),
    id_empleado_reserva integer REFERENCES empleado (id_empleado),
    reservada_hasta timestamp without time zone,
    id_tienda_reclamo integer REFERENCES tienda (id_tienda),
    reclamada_en timestamp without time zone,
    id_empleado_emisor integer REFERENCES empleado (id_empleado),
    creada_en timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT receta_emitida_estado_check CHECK (estado IN ('EMITIDA', 'RESERVADA', 'RECLAMADA', 'ANULADA')),
    CONSTRAINT receta_emitida_reserva_check CHECK (estado <> 'RESERVADA' OR (id_tienda_reserva IS NOT NULL AND reservada_hasta IS NOT NULL)),
    CONSTRAINT receta_emitida_reclamo_check CHECK (estado <> 'RECLAMADA' OR (id_tienda_reclamo IS NOT NULL AND reclamada_en IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS receta_emitida_medicamento (
    id_receta_emitida integer NOT NULL REFERENCES receta_emitida (id_receta_emitida),
    id_medicamento integer NOT NULL REFERENCES medicamento (id_medicamento),
    cantidad_autorizada integer NOT NULL,
    PRIMARY KEY (id_receta_emitida, id_medicamento),
    CONSTRAINT receta_emitida_medicamento_cantidad_check CHECK (cantidad_autorizada > 0)
);

-- Una tienda informó una dispensación de una receta que ya reclamó otra: no se descarta en silencio (regla 5).
-- Queda aquí, con el aviso completo, para revisión de la red.
CREATE TABLE IF NOT EXISTS receta_conflicto (
    id_conflicto bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_receta_emitida integer REFERENCES receta_emitida (id_receta_emitida),
    codigo character varying(40) NOT NULL,
    id_tienda_origen integer NOT NULL,
    motivo character varying(200) NOT NULL,
    payload jsonb NOT NULL,
    creado_en timestamp with time zone NOT NULL DEFAULT now(),
    resuelto boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_receta_emitida_documento ON receta_emitida (paciente_documento);
CREATE INDEX IF NOT EXISTS idx_receta_emitida_estado ON receta_emitida (estado);
