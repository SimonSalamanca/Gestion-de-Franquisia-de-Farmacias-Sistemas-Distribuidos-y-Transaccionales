CREATE TABLE IF NOT EXISTS control_acceso (
    id_empleado integer PRIMARY KEY REFERENCES empleado (id_empleado),
    epoch bigint NOT NULL DEFAULT 1,
    intentos_en_epoch integer NOT NULL DEFAULT 0,
    estado character varying(20) NOT NULL DEFAULT 'ACTIVO',
    bloqueado_hasta timestamp with time zone,
    provisional boolean NOT NULL DEFAULT false,
    provisional_hasta timestamp with time zone,
    id_snapshot bigint NOT NULL DEFAULT 0,
    CONSTRAINT control_acceso_estado_check CHECK (estado IN ('ACTIVO', 'BLOQUEADO'))
);

CREATE TABLE IF NOT EXISTS bloqueo_canonico (
    id_empleado integer NOT NULL REFERENCES empleado (id_empleado),
    epoch bigint NOT NULL,
    bloqueado_hasta timestamp with time zone NOT NULL,
    PRIMARY KEY (id_empleado, epoch)
);

CREATE TABLE IF NOT EXISTS intento_acceso (
    id_intento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key uuid NOT NULL UNIQUE,
    usuario_intentado character varying(60) NOT NULL,
    id_empleado integer,
    resultado character varying(40) NOT NULL,
    fecha_hora timestamp with time zone NOT NULL DEFAULT now(),
    detalle character varying(400)
);

CREATE TABLE IF NOT EXISTS auth_operacion (
    idempotency_key uuid PRIMARY KEY,
    payload_hmac character(64) NOT NULL,
    resultado_http integer NOT NULL,
    cuerpo_json jsonb NOT NULL,
    token_entrega text,
    creado_en timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sesion_activa (
    id_sesion uuid PRIMARY KEY,
    token_hash character(64) NOT NULL UNIQUE,
    id_empleado integer NOT NULL REFERENCES empleado (id_empleado),
    id_tienda integer NOT NULL,
    nodo_emisor character varying(10) NOT NULL,
    expira_en timestamp with time zone NOT NULL,
    revocada boolean NOT NULL DEFAULT false,
    creado_en timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS replica_evento (
    id_evento bigint PRIMARY KEY,
    id_tienda_destino integer,
    tipo_evento character varying(40) NOT NULL,
    version_credencial bigint NOT NULL DEFAULT 1,
    payload jsonb NOT NULL,
    creado_en timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS replica_cursor (
    id_tienda integer PRIMARY KEY,
    ultimo_evento_visto bigint NOT NULL DEFAULT 0,
    ultimo_ack_en timestamp with time zone
);

CREATE TABLE IF NOT EXISTS inbox_sync (
    id_tienda_origen integer NOT NULL,
    idempotency_key uuid NOT NULL,
    tipo_evento character varying(40) NOT NULL,
    payload jsonb NOT NULL,
    aplicado_en timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (id_tienda_origen, idempotency_key)
);

